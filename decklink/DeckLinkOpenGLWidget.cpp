void DeckLinkOpenGLWidget::setFrame(com_ptr<IDeckLinkVideoFrame> frame)
{
    if (!frame)
    {
        qDebug() << "[DeckLinkOpenGLWidget] Received null frame!";
        return;
    }

    // qDebug() << "[DeckLinkOpenGLWidget] Received frame:" << frame.get();

    if (m_deckLinkScreenPreviewHelper)
    {
        m_deckLinkScreenPreviewHelper->SetFrame(frame.get());
        update();
    }
}

void DeckLinkOpenGLWidget::setSharedDelegate(const com_ptr<DeckLinkOpenGLDelegate> &delegate)
{
    std::lock_guard<std::mutex> lock(m_mutex);

    if (!delegate)
        return;

    // Disconnect old delegate if it existed
    if (m_delegate)
        disconnect(m_delegate.get(), nullptr, this, nullptr);

    m_delegate = delegate;

    connect(m_delegate.get(), &DeckLinkOpenGLDelegate::frameArrived, this, &DeckLinkOpenGLWidget::setFrame, Qt::QueuedConnection);
}

com_ptr<DeckLinkOpenGLDelegate> DeckLinkOpenGLWidget::delegate()
{
    std::lock_guard<std::mutex> lock(m_mutex);
    return m_delegate;
}

void DeckLinkOpenGLWidget::setFlipStep(int step)
{
    std::lock_guard<std::mutex> lock(m_mutex);
    m_flipStep = step % 5;
    update();
}

