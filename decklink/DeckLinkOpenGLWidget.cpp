{
    // qDebug() << "initialize GL";
    if (m_deckLinkScreenPreviewHelper)
    {
        std::lock_guard<std::mutex> lock(m_mutex);
        m_deckLinkScreenPreviewHelper->InitializeGL();
    }
}

